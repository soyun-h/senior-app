export function getPersonaCard(id: CharacterId): PersonaCard {
  return PERSONA_CARDS[id] ?? PERSONA_CARDS.char1;
}

/** 설정 카드 한 장을 system prompt용 글로 만든다. {호칭}은 호출하는 쪽에서 fill()로 바꾼다 */
export function personaCardText(id: CharacterId): string {
  const c = getPersonaCard(id);
  return [
    `[설정 카드 — ${CHARACTER_GUIDE_TITLE}]`,
    `다른 손주와 가장 다른 점: ${c.difference}`,
    `사는 이야기: ${c.background}`,
    `어르신을 대하는 태도: ${c.attitude}`,
    `말투: ${c.speech}`,
    `말버릇: ${c.catchphrases.join(' / ')}`,
    `하지 않는 말: ${c.avoid}`,
    `칭찬하는 방식: ${c.praise}`,
    `걱정하는 방식: ${c.worry}`,
    `첫인사(통화를 시작할 때 항상): ${c.greeting}`,
    `끝인사(통화를 끝낼 때 항상): ${c.goodbye}`,
    RARE_LINES[id] ? `아주 가끔만(통화 세 번에 한 번 이하) 하는 말: ${RARE_LINES[id]}` : '',
    '상황별 예시 대사:',
    ...c.examples.map(([situation, line]) => `- ${situation}: ${line}`),
  ].filter(Boolean).join('\n');
}

export function guideRulesText(): string {
  return [
    '[대화 가이드]',
    ...GUIDE_SECTIONS.flatMap(s => [`<${s.title}>`, ...s.rules.map(r => '- ' + r)]),
  ].join('\n');
}

export function memoryText(memory?: string | null): string {
  const m = (memory ?? '').trim();
  return ['[이 어르신에 대해 알고 있는 것]', m || '없음 (첫 통화)'].join('\n');
}

/** 통화가 끝날 때 한 번 돌려서 기억 메모를 갱신하는 프롬프트. 메모는 어르신마다 하나, 다섯 명이 같이 쓴다 */
export const MEMORY_MAX_LINES = 10;

export function buildMemorySummaryPrompt(previousMemory: string, transcript: string): string {
  return [
    '아래는 어르신과 손주 캐릭터의 통화 내용이야.',
    '[기존 메모]와 [오늘 대화]를 합쳐서 새 메모를 만들어.',
    '',
    '규칙',
    '1. 다음 통화에서 꺼낼 만한 것만 남겨: 가족·지인 이름, 좋아하는 것, 취미, 다가오는 일정, 최근 있었던 일.',
    `2. 한 줄에 한 가지, 최대 ${MEMORY_MAX_LINES}줄. 넘치면 오래되고 덜 중요한 줄부터 버려.`,
    '3. 어르신이 직접 말한 것만 적어. 추측하거나 지어내지 마.',
    '4. 바뀐 내용은 새 내용으로 고쳐.',
    '5. 몸 상태는 어르신이 말한 그대로만 짧게 적고, 병 이름을 추측해서 붙이지 마.',
    '6. 돈, 계좌, 비밀번호, 주민번호는 절대 적지 마.',
    '7. 메모만 출력해. 설명은 붙이지 마.',
    '',
    '[기존 메모]',
    previousMemory.trim() || '없음',
    '',
    '[오늘 대화]',
    transcript.trim(),
  ].join('\n');
}

